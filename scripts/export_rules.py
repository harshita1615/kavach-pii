"""Export Kavach's rule data from Python to the extension.

    python scripts/export_rules.py

Writes extension/src/core/rules.json: keyword lists, known UPI handles and bank
codes, scores and thresholds. Python is the single source of truth for this
data; the TypeScript port imports the JSON instead of copying the values. CI
re-runs this script and fails if the committed file is out of date.

Only data lives here. Regular expressions are ported by hand and checked by
the parity test (scripts/export_parity.py).
"""

from __future__ import annotations

import json
from pathlib import Path

from kavach import SYSTEM_PROMPT, engine
from kavach.context import keywords_en, keywords_hi, scorer
from kavach.context.scorer import keywords_for
from kavach.detectors import aadhaar, bank, email, gstin, ifsc, pan, phone, upi
from kavach.masking import placeholders
from kavach.types import EntityType

OUT = Path(__file__).resolve().parent.parent / "extension" / "src" / "core" / "rules.json"


def rules() -> dict:
    return {
        "_comment": "Generated by scripts/export_rules.py from the Python package. Do not edit.",
        "entityTypes": [e.value for e in EntityType],
        "keywords": {e.value: list(keywords_for(e)) for e in EntityType},
        "notPiiLabels": list(keywords_en.NOT_PII_LABELS + keywords_hi.NOT_PII_LABELS),
        "contextWindowBefore": scorer.WINDOW_BEFORE,
        "contextWindowAfter": scorer.WINDOW_AFTER,
        "labelWindow": scorer.LABEL_WINDOW,
        "defaultThreshold": engine.DEFAULT_THRESHOLD,
        "contextBoost": engine.CONTEXT_BOOST,
        "notPiiLabelPenalty": engine.NOT_PII_LABEL_PENALTY,
        "numericEntities": sorted(e.value for e in engine.NUMERIC),
        "specificity": [e.value for e in engine.SPECIFICITY],
        "placeholderMaxLength": placeholders.MAX_LENGTH,
        "systemPrompt": SYSTEM_PROMPT,
        "scores": {
            "AADHAAR": aadhaar.BASE_SCORE,
            "PAN": pan.BASE_SCORE,
            "UPI_KNOWN_HANDLE": upi.KNOWN_HANDLE_SCORE,
            "UPI_UNKNOWN_HANDLE": upi.UNKNOWN_HANDLE_SCORE,
            "IFSC_KNOWN_BANK": ifsc.KNOWN_BANK_SCORE,
            "IFSC_UNKNOWN_BANK": ifsc.UNKNOWN_BANK_SCORE,
            "BANK_ACCOUNT": bank.BASE_SCORE,
            "PHONE_INTERNATIONAL": phone.INTERNATIONAL_PREFIX_SCORE,
            "PHONE": phone.BASE_SCORE,
            "GSTIN": gstin.BASE_SCORE,
            "EMAIL": email.BASE_SCORE,
        },
        "panHolderTypes": pan.HOLDER_TYPES,
        "gstinStateCodes": sorted(gstin.VALID_STATE_CODES),
        "upiKnownHandles": sorted(upi.KNOWN_HANDLES),
        "ifscKnownBankCodes": sorted(ifsc.KNOWN_BANK_CODES),
    }


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(rules(), ensure_ascii=False, indent=2) + "\n"
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(OUT.parents[3])}")


if __name__ == "__main__":
    main()
