def record(k: Kavach, text: str, case_id: str) -> dict:
    detections = [[d.entity_type.value, d.start, d.end, d.score] for d in k.scan(text)]
    return {"id": case_id, "text": text, "detections": detections, "masked": k.session().mask(text)}


def main() -> None:
    k = Kavach()
    cases = []
    for path in DATASETS:
        with path.open(encoding="utf-8") as f:
            for line in f:
                r = json.loads(line)
                cases.append(record(k, r["text"], r["id"]))
    for i, text in enumerate(EDGE_CASES):
        cases.append(record(k, text, f"edge-{i:03d}"))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "_comment": "Generated by scripts/export_parity.py. Do not edit.",
        "kavach": __version__,
        "cases": cases,
    }
    with OUT.open("w", encoding="utf-8", newline="\n") as f:
        json.dump(payload, f, ensure_ascii=False, indent=0)
        f.write("\n")
    n = sum(len(c["detections"]) for c in cases)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(cases)} cases, {n} detections")


if __name__ == "__main__":
    main()
